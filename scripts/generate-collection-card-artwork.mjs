import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicCards = path.join(root, 'apps/web/public/cards');
const manifest = JSON.parse(
  await readFile(path.join(root, 'artwork/cards/manifest.json'), 'utf8'),
);
const widths = [192, 384, 512, 768];
const sharedHomeVariants = new Set(['axiomar', 'quillip']);
const variantDirectory = path.join(publicCards, 'collection');
const sourceSetByUrl = {};

await mkdir(variantDirectory, { recursive: true });

for (const card of manifest.cards) {
  const match = /^\/cards\/([a-z0-9-]+)\.webp$/.exec(card.optimized);
  if (!match) throw new Error('Unexpected catalogue artwork path');
  const name = match[1];
  const source = path.join(publicCards, name + '.webp');
  const sources = [];

  for (const width of widths) {
    let url;
    if ((width === 384 || width === 768) && sharedHomeVariants.has(name)) {
      url = '/cards/home/' + name + '-' + width + '.webp';
      const metadata = await sharp(
        path.join(publicCards, 'home', name + '-' + width + '.webp'),
      ).metadata();
      if (metadata.width !== width || metadata.height !== width) {
        throw new Error('Unexpected homepage artwork dimensions');
      }
    } else {
      url = '/cards/collection/' + name + '-' + width + '.webp';
      await sharp(source)
        .resize(width, width, { fit: 'inside', kernel: 'lanczos3' })
        .webp({ quality: 82, effort: 6 })
        .toFile(path.join(variantDirectory, name + '-' + width + '.webp'));
    }
    sources.push(url + ' ' + width + 'w');
  }
  sources.push(card.optimized + ' 1024w');
  sourceSetByUrl[card.optimized] = sources.join(', ');
}

const lines = [
  '// Generated by scripts/generate-collection-card-artwork.mjs from the catalogue manifest.',
  '// Only packaged 1024px card images have verified responsive variants.',
  'export const collectionArtworkSrcSets: Readonly<Record<string, string>> = {',
  ...Object.entries(sourceSetByUrl).map(
    ([url, srcSet]) =>
      '  ' + JSON.stringify(url) + ': ' + JSON.stringify(srcSet) + ',',
  ),
  '};',
  '',
];

const generatedSourcePath = path.join(
  root,
  'apps/web/src/components/cards/collection-artwork-assets.ts',
);
await writeFile(
  generatedSourcePath,
  await prettier.format(lines.join('\n'), {
    ...(await prettier.resolveConfig(generatedSourcePath)),
    filepath: generatedSourcePath,
  }),
);

console.log(
  'Generated responsive assets for ' +
    Object.keys(sourceSetByUrl).length +
    ' catalogue cards.',
);
